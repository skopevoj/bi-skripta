// Regenerates content/index.ts from the files present in content/chapters, content/bank and content/tests.
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'content')
const names = (d) => (existsSync(join(root, d)) ? readdirSync(join(root, d)).filter((f) => f.endsWith('.ts')).map((f) => f.slice(0, -3)).sort() : [])
const chaps = names('chapters')
const order = ['ch', 'wiki', 'mocks']
const banks = names('bank').sort((a, b) => order.findIndex((o) => a.startsWith(o)) - order.findIndex((o) => b.startsWith(o)) || a.localeCompare(b))
const hasTests = existsSync(join(root, 'tests', 'tests.ts'))
const hasCuration = existsSync(join(root, 'curation.ts'))

const out = `// GENERATED by scripts/gen-index.mjs — aggregates all content for the app.
import type { Chapter, MockTest, Question } from './types'

${chaps.map((c) => `import { ${c} } from './chapters/${c}'`).join('\n')}

${banks.map((b) => `import { ${b} } from './bank/${b}'`).join('\n')}
${hasTests ? "import { tests as mockTests } from './tests/tests'" : ''}
${hasCuration ? "import { EXCLUDED_IDS } from './curation'" : ''}

export * from './types'
${hasCuration ? "export { EXCLUDED_IDS }" : 'export const EXCLUDED_IDS: ReadonlySet<string> = new Set()'}

export const chapters: Chapter[] = [${chaps.join(', ')}]

// All questions from the banks minus the curated exclusions (duplicates, off-syllabus topics).
export const questions: Question[] = [${banks.map((b) => `...${b}`).join(', ')}]${hasCuration ? '.filter((q) => !EXCLUDED_IDS.has(q.id))' : ''}

export const questionById: Map<string, Question> = new Map(questions.map((q) => [q.id, q]))

export const tests: MockTest[] = ${hasTests ? 'mockTests' : '[]'}
`
writeFileSync(join(root, 'index.ts'), out)
console.log(`index.ts: ${chaps.length} chapters, ${banks.length} banks, tests: ${hasTests}, curation: ${hasCuration}`)
